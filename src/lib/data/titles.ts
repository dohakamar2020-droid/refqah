/** اللقب المقترح الأول لهذا الحديث (أو لقب عام إن لم يوجد اقتراح). */
export function suggestedTitleFor(order: number): string {
  const list = HADITH_TITLES[order];
  return list?.[0] ?? GENERAL_TITLES[0];
}

/** كل الاقتراحات: لقب هذا الحديث أولًا، ثم بقية ألقاب الحديث، ثم العامة. */
export function titleSuggestionsFor(order: number): string[] {
  const own = HADITH_TITLES[order] ?? [];
  const seen = new Set<string>();
  return [...own, ...GENERAL_TITLES].filter((t) => {
    if (seen.has(t)) return false;
    seen.add(t);
    return true;
  });
}
